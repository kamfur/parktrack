                    foreach ($suspicious_words as $word) {
                        if (strpos($email_lower, $word) !== false) {
                            $emailErr = "Adres email zawiera podejrzane słowa.";
                            $formValid = false;
                            break;
                        }
                    }
                    
                    // Sprawdź czy email nie jest zbyt prosty (np. a@a.com)
                    if (strlen($email_domain) < 4 || strlen(explode('@', $email)[0]) < 2) {
                        $emailErr = "Adres email wygląda na nieprawdziwy.";
                        $formValid = false;
                    }
                }
