                        if (suspiciousDomains.includes(domain.toLowerCase())) {
                            this.style.borderColor = '#ff4400';
                            this.title = 'Nieprawidłowa domena email';
                        } else {
                            this.style.borderColor = '';
                            this.title = '';
                        }
                    } else {
                        this.style.borderColor = '';
                        this.title = '';
                    }
                });
